"""Original deterministic PCM effects. Generates assets; never plays audio."""
import math, random, struct, wave
from pathlib import Path
SR=48000
out=Path('public/assets/online/action-audio-v1');out.mkdir(parents=True,exist_ok=True)
def save(name,data):
 peak=max(abs(v)for v in data)or 1
 with wave.open(str(out/name),'wb')as w:
  w.setparams((1,2,SR,0,'NONE','not compressed'))
  w.writeframes(b''.join(struct.pack('<h',round(max(-1,min(1,v/peak*.88))*32767))for v in data))
rng=random.Random(251125)
# Metal biting stone: a short edge contact followed by a deeper, descending hit.
data=[];low=0
for i in range(int(SR*1.65)):
 t=i/SR;n=rng.uniform(-1,1);low+=.032*(n-low)
 attack=min(1,t/.0015);tail=min(1,(1.65-t)/.12)
 crack=n*.25*math.exp(-t*55)+low*1.65*math.exp(-t*10)
 phase=2*math.pi*(43*t+1.4*(1-math.exp(-t*30)))
 body=(math.sin(phase)*.66+math.sin(2*phase)*.16)*math.exp(-t*5.7)
 metal=sum(math.sin(2*math.pi*f*t)*a*math.exp(-t*d)for f,a,d in[(470,.14,8),(734,.09,8),(1189,.056,10),(1776,.021,13)])
 grit=0
 for delay in [.065,.113,.179,.247,.331,.442]:
  q=t-delay
  if q>=0:grit+=(n*.045+low*.12)*math.exp(-q*42)
 data.append((crack+body+metal+grit)*attack*tail)
# Quiet hall reflection, without a smeared attack.
dry=data[:]
for delay,gain in[(.057,.13),(.109,.09),(.183,.055)]:
 k=round(delay*SR)
 for i in range(k,len(data)):data[i]+=dry[i-k]*gain
save('boss-sword-stab-deep.wav',data)
# One 260ms animation cycle: two mechanical knocks and small capsule clatters.
data=[]
for i in range(round(SR*.26)):
 t=i/SR;v=0
 for delay,pitch,gain in[(.008,175,.8),(.055,1050,.18),(.138,210,.7),(.190,1350,.2),(.221,840,.12)]:
  q=t-delay
  if q>=0:v+=gain*(math.sin(2*math.pi*pitch*q)*math.exp(-q*85)+rng.uniform(-1,1)*.45*math.exp(-q*150))
 v*=min(1,t/.003,(.26-t)/.014)
 data.append(v)
save('gacha-rattle.wav',data)
# A dying growl: descending glottal pulses, dark vowel formants and a breath tail.
data=[];voice_phase=0;breath=0;voice_rng=random.Random(271112)
for i in range(round(SR*1.65)):
 t=i/SR
 f0=58+52*math.exp(-t*2.4)+2.2*math.sin(2*math.pi*7.1*t)
 voice_phase+=2*math.pi*f0/SR
 breath+=.06*(voice_rng.uniform(-1,1)-breath)
 envelope=min(1,t/.12)*math.exp(-t*1.65)*min(1,(1.65-t)/.32)
 throat=0
 for harmonic in range(1,15):
  hz=f0*harmonic
  resonances=.75*math.exp(-((hz-(450-155*t))/125)**2)+.43*math.exp(-((hz-815)/195)**2)
  throat+=math.sin(voice_phase*harmonic)*(.52/harmonic+resonances*.15)
 grit=.86+.14*math.sin(2*math.pi*(33*t-3*t*t))
 reflection=data[i-2208]*.12 if i>=2208 else 0
 data.append((throat*grit+breath*(.24+t*.18))*envelope+reflection)
save('boss-last-groan.wav',data)
# One short layer per element, mixed alongside the weapon's existing contact cue.
for kind in ('fire','thunder','water','ice','light','dark'):
 r=random.Random(270113);data=[];lp=0
 for i in range(round(SR*.36)):
  t=i/SR;n=r.uniform(-1,1);lp+=.058*(n-lp)
  if kind=='fire':
   v=lp*1.9*math.exp(-t*12)+(n-lp)*.27*math.exp(-t*29)+.23*math.sin(2*math.pi*(104*t+36*t*t))*math.exp(-t*16)
  elif kind=='thunder':
   sparks=sum(math.exp(-(t-delay)*90) for delay in (0,.034,.064,.103) if t>=delay)
   v=(n*.48+lp*1.45)*sparks+.39*math.sin(2*math.pi*(82*t+45*t*t))*math.exp(-t*11)
  elif kind=='water':
   v=lp*.9*math.exp(-t*17)
   for delay,f in ((0,460),(.037,590),(.095,385)):
    q=t-delay
    if q>=0:v+=.4*math.sin(2*math.pi*(f*q+540*q*q))*math.exp(-q*33)
  elif kind=='ice':
   v=n*.26*math.exp(-t*95)+sum(.21*math.sin(2*math.pi*f*t)*math.exp(-t*a) for f,a in ((1220,18),(1833,17),(2732,21),(3425,24)))
  elif kind=='light':
   v=sum(.27*math.sin(2*math.pi*f*(t-delay))*math.exp(-(t-delay)*14) for f,delay in ((720,0),(1080,.036),(1440,.064)) if t>=delay)
  else:
   v=(.49*math.sin(2*math.pi*(145*t-95*t*t))+.23*math.sin(2*math.pi*(216*t-150*t*t))+lp*.55)*math.exp(-t*10)
  data.append(v*min(1,t/.003,(.36-t)/.045))
 save('element-hit-'+kind+'.wav',data)
(out/'README.txt').write_text('Original procedural sound effects for Chari Dungeon: ZERO. Generated by scripts/generate-action-audio.py. No third-party recordings or voices. 48kHz mono PCM16. No playback during generation.\n',encoding='utf-8')
print('Generated boss, gacha and elemental cues; no playback.')
